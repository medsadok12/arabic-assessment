import { describe, it, expect } from 'vitest';
import { completeSukun } from './arabic-tashkeel';

/* إكمال السكون الناقص قبل النطق — بلاغ «أَوْ غَيرَ» قُرئت «غيرِ» */

describe('إكمال سكون حرف اللين', () => {
  it('الجملة التي أخطأ فيها الصوت: غَيرَ ← غَيْرَ، والباقي كما هو', () => {
    const s = 'سَوَاءٌ كَانُوا نَاطِقِينَ بِالْعَرَبِيَّةِ أَوْ غَيرَ نَاطِقِينَ بِهَا.';
    expect(completeSukun(s)).toBe('سَوَاءٌ كَانُوا نَاطِقِينَ بِالْعَرَبِيَّةِ أَوْ غَيْرَ نَاطِقِينَ بِهَا.');
  });

  it('واو وياء بعد فتحة وقبل متحرك تُسكَّن', () => {
    expect(completeSukun('يَومُ')).toBe('يَوْمُ');
    expect(completeSukun('الْيَومِ')).toBe('الْيَوْمِ');
    expect(completeSukun('خَوفٍ')).toBe('خَوْفٍ');
    expect(completeSukun('مَوقِعٌ')).toBe('مَوْقِعٌ');
  });

  it('لا يُخمَّن حيث قد يكون الساقط فتحة: حرف زائد، وزن فَعَلَان/فَعَال، شدّة بعده', () => {
    for (const w of ['سَيكُونُ', 'وَيلعَبُ', 'حَيوَانٌ', 'طَيرَانٌ', 'حَيوَانَاتٌ', 'تَوقَّفَ', 'تَيسَّرَ']) {
      expect(completeSukun(w)).toBe(w);
    }
  });

  it('لا يمس ما لا لبس فيه: المدّ، المشكول، الكلمة بلا تشكيل، النص غير العربي', () => {
    for (const w of ['نَاطِقِينَ', 'يَقُولُونَ', 'غَيْرَ', 'أَيَّامٌ', 'قَوِيٌّ', 'جَوَابٌ', 'غير', 'كيف حالك', 'Hello 3.5 🌟', '']) {
      expect(completeSukun(w)).toBe(w);
    }
  });
});

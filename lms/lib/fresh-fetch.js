export function freshUrl(url) {
  return `${url}${url.includes('?') ? '&' : '?'}t=${Date.now()}`;
}

export function freshFetch(url, opts = {}) {
  return fetch(freshUrl(url), { ...opts, cache: 'no-store' });
}

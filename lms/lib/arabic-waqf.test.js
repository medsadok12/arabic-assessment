import { describe, it, expect } from 'vitest';
import { applyWaqf } from './arabic-waqf.js';

/* الوقف بالسكون: آخر الكلمة قبل الوقفة يُنطق ساكناً، ووسط الجملة كما هو */

describe('الوقف بالسكون', () => {
  it.each([
    ['تنوين الضم ← سكون', 'أَنَا فِيلٌ صَغِيرٌ.', 'أَنَا فِيلٌ صَغِيرْ.'],
    ['الحركة في آخر الكلام ← سكون', 'يَا بَطَلُ', 'يَا بَطَلْ'],
    ['تنوين الفتح ← ألف (ووسط الجملة يبقى)', 'أَهْلًا بِكَ وَسَهْلًا!', 'أَهْلًا بِكَ وَسَهْلَا!'],
    ['تنوين الفتح على الألف', 'كتاباً.', 'كتابَا.'],
    ['تنوين الفتح مع الشدة', 'جِدًّا.', 'جِدَّا.'],
    ['تنوين الفتح قبل الألف المقصورة', 'هُدًى.', 'هُدَى.'],
    ['تنوين الفتح على الهمزة', 'مَاءً.', 'مَاءَا.'],
    ['التاء المربوطة ← هاء ساكنة', 'مَدْرَسَةٌ جَمِيلَةٌ، وَكَبِيرَةٌ.', 'مَدْرَسَةٌ جَمِيلَهْ، وَكَبِيرَهْ.'],
    ['الشدة تبقى', 'رَمَادِيٌّ.', 'رَمَادِيّ.'],
    ['حروف المد لا تتغير', 'فِي. أَنَا! إِلَى؟', 'فِي. أَنَا! إِلَى؟'],
    ['الضمير قبل السؤال', 'مَعَكِ؟ هُوَ؟', 'مَعَكْ؟ هُوْ؟'],
    ['علامات التنصيص والرموز لا تمنع الوقف', '«الْمَكْتَبَةُ». يَا بَطَلُ 🌟', '«الْمَكْتَبَهْ». يَا بَطَلْ 🌟'],
    ['الكسرة وتنوينها في آخر النص', 'لَسْتُ مُتَأَكِّدًا بِدِقَّةٍ', 'لَسْتُ مُتَأَكِّدًا بِدِقَّهْ'],
    ['وسط الجملة لا يُمس', 'كِتَابٌ جَمِيلٌ وَقَلَمٌ.', 'كِتَابٌ جَمِيلٌ وَقَلَمْ.'],
    ['نص غير عربي لا يتغير', 'OK. Hello!', 'OK. Hello!'],
  ])('%s', (_, input, expected) => {
    expect(applyWaqf(input)).toBe(expected);
  });
  it('نص فارغ أو غير نصي لا يكسر شيئاً', () => {
    expect(applyWaqf('')).toBe('');
    expect(applyWaqf(undefined)).toBe('');
  });
});

/**
 * يحدّد المستوى بناءً على *أول نقطة* تبدأ عندها الإجابات الخاطئة
 * بالتراكم — لا على عمر الطفل. answers: مصفوفة من 15 عنصراً بنفس ترتيب
 * QUESTIONS، كل عنصر { isCorrect }.
 *
 * ملاحظة تصحيح صريحة على الصياغة الأصلية: النص المصدر يصف شرط "البراعم"
 * بأنه تعثّر (>2 خطأ) عبر كامل نطاق الأسئلة 6-15 — لكن هذا يتعارض حرفياً
 * مع تعريف "المستكشفين" نفسه (صحيح في 1-10، متعثر في 11-15 تحديداً)،
 * لأن طفلاً صحيحاً بالكامل في 6-10 ومتعثراً بالكامل في 11-15 يحقق كلا
 * الشرطين معاً بالنص الحرفي. الحل المعتمد هنا (يطابق فعلياً وصف "البراعم"
 * النوعي — "يحتاج للتأسيس القرائي ومعرفة الحروف"، وهو ما يقيسه تحديداً
 * نطاق 6-10 لا 11-15): فحص التعثر المبكر في نطاق 6-10 فقط أولاً (بوابة
 * "المستكشفين")، ثم نطاق الإتقان الكامل (13/15+) لـ"المبدعين"، وإلا
 * فالنتيجة الافتراضية "المستكشفون" — بالضبط ما يصفه تعريفهم الحرفي.
 */
export function computeLevel(answers) {
  const wrongIn = (from, to) => answers.slice(from, to).filter(a => !a?.isCorrect).length;
  const totalCorrect = answers.filter(a => a?.isCorrect).length;

  if (wrongIn(5, 10) > 2) return LEVELS.buds;        // تعثّر مبكر في نطاق 6-10
  if (totalCorrect >= 13) return LEVELS.creators;     // إتقان شبه كامل
  return LEVELS.explorers;                             // الحالة الوسطى الافتراضية
}

// بمنطق applyJumpLogic/JUMP_THRESHOLD المعتمد في التقييم الحقيقي متعدد
// المستويات (App.jsx)؛ هذا اختبار مسطّح بلا مستويات تصاعدية، فقط تصنيف
// نهائي واحد من نسبة الإجابات الصحيحة على الـ12 سؤالاً. الأسماء (مبتدئ/
// متوسط/متقدم) مطابقة عمداً لأسماء LEVELS في data/questions.js لتماسك
// العلامة عبر التطبيقين.
export function levelFromScore(pct) {
  if (pct >= 75) return { label: 'متقدم', icon: '🎓' };
  if (pct >= 45) return { label: 'متوسط', icon: '📚' };
  return { label: 'مبتدئ', icon: '🌱' };
}
